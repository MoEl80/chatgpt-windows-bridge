# ChatGPT Windows Bridge - install-task.ps1 (setup.ps1 runs this for you)
# Registers a per-user logon task that runs start.mjs (server + tunnel-client) hidden (wscript launcher,
# no console window), restarts it on failure, and starts it now. Remove with: install-task.ps1 -Remove
param(
  [switch]$Remove,
  [string]$TaskName = "ChatGPT-Windows-Bridge",
  [int]$Port = 8797
)
$ErrorActionPreference = "Stop"
if ($Remove) {
  Stop-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
  Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false -ErrorAction SilentlyContinue
  Write-Host "Removed task '$TaskName'."
  exit 0
}

$here = Split-Path -Parent $MyInvocation.MyCommand.Definition
$nodeExe = (Get-Command node -ErrorAction Stop).Source
$vbsPath = Join-Path $here "run-server.vbs"
$logPath = Join-Path $here ".state\server.log"
New-Item -ItemType Directory -Force -Path (Join-Path $here ".state") | Out-Null
$vbs = @(
  "' ChatGPT Windows Bridge hidden launcher - generated by install-task.ps1; re-run it instead of editing.",
  "Option Explicit",
  "Dim sh, rc",
  "Set sh = CreateObject(""WScript.Shell"")",
  "sh.CurrentDirectory = ""$here""",
  "sh.Environment(""PROCESS"")(""CHATGPT_BRIDGE_PORT"") = ""$Port""",
  "rc = sh.Run(""cmd /c """"""""$nodeExe"""" start.mjs >> """"$logPath"""" 2>&1"""""", 0, True)",
  "WScript.Quit rc"
)
[System.IO.File]::WriteAllText($vbsPath, ($vbs -join "`r`n") + "`r`n")

$action = New-ScheduledTaskAction -Execute "$env:SystemRoot\System32\wscript.exe" -Argument "`"$vbsPath`"" -WorkingDirectory $here
$trigger = New-ScheduledTaskTrigger -AtLogOn -User $env:USERNAME
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable `
  -ExecutionTimeLimit ([TimeSpan]::Zero) -RestartCount 999 -RestartInterval (New-TimeSpan -Minutes 1) -MultipleInstances IgnoreNew
Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Settings $settings `
  -Description "ChatGPT Windows Bridge: MCP server + OpenAI tunnel-client ($here)" -Force | Out-Null
Start-ScheduledTask -TaskName $TaskName
Write-Host "Task '$TaskName' registered and started (node $nodeExe, port $Port)."
